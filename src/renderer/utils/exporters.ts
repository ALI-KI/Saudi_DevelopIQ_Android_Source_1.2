const officialPrimaryLogoUrl = new URL('../../../assets/brand/developiq-primary.png', import.meta.url).href;
const officialAppIconUrl = new URL('../../../assets/brand/developiq-app-icon.png', import.meta.url).href;
const bytes = (buffer: ArrayBuffer) => Array.from(new Uint8Array(buffer));
const desktopAPI = () => {
  if (!window.desktopAPI) throw new Error('desktopAPI preload bridge is not available.');
  return window.desktopAPI;
};

const imageUrlToDataUrl = async (url: string) => {
  const response = await fetch(url);
  const blob = await response.blob();
  return await new Promise<string>((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(String(reader.result));
    reader.onerror = () => reject(reader.error ?? new Error('Could not read brand image.'));
    reader.readAsDataURL(blob);
  });
};

const loadImage = async (url: string) => await new Promise<HTMLImageElement>((resolve, reject) => {
  const image = new Image();
  image.onload = () => resolve(image);
  image.onerror = () => reject(new Error(`Could not load image: ${url}`));
  image.src = url;
});

const logoToPng = async (dataUrl?: string) => {
  if (!dataUrl || typeof document === 'undefined') return null;
  if (dataUrl.startsWith('data:image/png')) return dataUrl;
  return await new Promise<string | null>((resolve) => {
    const image = new Image();
    image.onload = () => {
      const canvas = document.createElement('canvas');
      canvas.width = Math.max(image.naturalWidth, 220);
      canvas.height = Math.max(image.naturalHeight, 120);
      const context = canvas.getContext('2d');
      if (!context) return resolve(null);
      context.clearRect(0, 0, canvas.width, canvas.height);
      context.drawImage(image, 0, 0, canvas.width, canvas.height);
      resolve(canvas.toDataURL('image/png'));
    };
    image.onerror = () => resolve(null);
    image.src = dataUrl;
  });
};

export const exportExcel = async (project: ProjectRecord, regulations: RegulationPack[], language: LanguageMode, company?: CompanyProfile) => {
  const scenario = project.scenarios.find((s) => s.id === project.activeScenarioId) ?? project.scenarios[0];
  const regulation = project.regulationSnapshots.find((r) => r.id === scenario.regulationId) ?? regulations.find((r) => r.id === scenario.regulationId);
  if (!regulation) throw new Error('No active regulation snapshot selected for export.');
  const result = runScenario(scenario, regulation);
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Saudi DevelopIQ - Riyadh Edition';
  const sheetNames = ['01_Summary','02_Development','03_Regulation','04_Parking','05_Financial_Inputs','06_Feasibility','07_Cash_Flow','08_Assumptions_Sources'];
  const sheets = sheetNames.map((name) => wb.addWorksheet(name, { views: [{ rightToLeft: language !== 'en' }] }));
  const [summary, development, regulationSheet, parking, inputs, feasibility, cashFlow, assumptions] = sheets;
  wb.company = company?.companyNameEn || 'Saudi DevelopIQ';
  const logoPng = await logoToPng(company?.logoDataUrl) ?? await imageUrlToDataUrl(officialPrimaryLogoUrl);
  if (logoPng) {
    const imageId = wb.addImage({ base64: logoPng, extension: 'png' });
    summary.addImage(imageId, { tl: { col: 3.2, row: 0.2 }, ext: { width: 140, height: 64 } });
  }
  summary.addRows([
    ['Saudi DevelopIQ - Riyadh Edition'],
    ['From Plot to Decision / من الأرض إلى قرار التطوير'],
    ['Generated by Saudi DevelopIQ - Riyadh Edition'],
    ['Project Name', project.info.name],
    ['Decision', L(result.decision.label, language)],
    ['Regulatory Applicability', 'NOT INDEPENDENTLY VERIFIED FOR THIS PARCEL'],
    ['Parcel Reference', [project.info.planNumber,project.info.plotNumber,project.info.deedNumber].filter(Boolean).join(' / ')],
    ['Plot Area', result.envelope.plotArea],
    ['Permitted GFA', result.envelope.permittedGfa],
    ['Achieved GFA', result.envelope.achievedGfa],
    ['Required Parking', result.parking.requiredSpaces],
    ['Surface Parking', result.parking.surfaceParking],
    ['Parking Layout', result.parking.parkingLayout]
  ]);
  development.addRow(['Floor','Coverage Limit','Geometry Limit','Zone Limit','FAR Limit','Final Allowed Area']);
  result.envelope.floorAreas.forEach((row) => development.addRow([row.floor, row.coverageLimit, row.geometryLimit, row.zoneLimit, row.farLimit, row.finalAllowedArea]));
  regulationSheet.addRows([
    ['Rule','Value','Authority','Source','Version','Verification Status','Override'],
    ['Regulation', L(regulation.name, language), L(regulation.authority, language), regulation.sourceReference, regulation.version, regulation.verificationStatus, 'No'],
    ['FAR', regulation.far.value ?? 'No FAR', L(regulation.authority, language), regulation.far.source, regulation.version, regulation.far.status, 'No'],
    ['Setbacks', JSON.stringify(regulation.setbacks.value), L(regulation.authority, language), regulation.setbacks.source, regulation.version, regulation.setbacks.status, 'No']
  ]);
  if (scenario.overrides.length) {
    regulationSheet.addRow([]);
    regulationSheet.addRow(['Rule','Regulatory Value','Used Value','Source','Reason','Timestamp']);
    scenario.overrides.forEach((override) => regulationSheet.addRow([override.field, override.originalValue === 'null' ? 'Not Defined' : override.originalValue, override.usedValue, 'USER_OVERRIDE', override.reason, override.createdAt]));
  }
  parking.addRows([
    ['Required Spaces', result.parking.requiredSpaces],
    ['Surface Parking', result.parking.surfaceParking],
    ['Auto Surface Parking', result.parking.autoSurfaceParking],
    ['Surface Parking Mode', result.parking.surfaceParkingMode],
    ['Street Parking Layout', result.parking.parkingLayout],
    ['Street Parking Rule', result.parking.parkingLayout === 'ANGLED_45' ? 'Street width >= 30m: angled 45 degree, 5.5m x 2.8m stalls, frontage / 2.8' : result.parking.parkingLayout === 'PERPENDICULAR' ? 'Street width < 30m: perpendicular parking, 5.5m x 2.8m stalls, frontage / 2.8' : 'Not applicable'],
    ['Spaces Per Basement', result.parking.spacesPerBasement],
    ['Required Basements After Surface Parking', result.parking.basementCountRequired],
    ['Provided Basements', scenario.basementCount],
    ['Total Provided Spaces', result.parking.providedSpaces],
    ['Balance', result.parking.balance],
    ['Status', result.parking.status]
  ]);
  inputs.addRows([
    ['Input','Value','Indicator'],
    ['Land Price', scenario.financial.landPrice, 'Input'],
    ['Structural Rate', scenario.financial.structuralRate, 'Input'],
    ['Finishing Rate', scenario.financial.finishingRate, 'Input'],
    ['MEP Rate', scenario.financial.mepRate, 'Input'],
    ['Selling Price Residential', scenario.financial.sellingPriceResidential, 'Input'],
    ['Sellable Efficiency', scenario.financial.sellableEfficiencyResidential, 'Assumption']
  ]);
  feasibility.addRows([
    ['Metric','Formula / Value'],
    ['Land Cost', { formula: `'02_Development'!F2*0+${result.financial.landCost}`, result: result.financial.landCost }],
    ['Construction Cost', result.financial.constructionCost],
    ['Total Cost', { formula: 'B2+B3+' + result.financial.softCosts, result: result.financial.totalCost }],
    ['Revenue', result.financial.revenue],
    ['Profit', { formula: 'B5-B4', result: result.financial.profit }],
    ['Profit Margin', { formula: 'B6/B5', result: result.financial.profitMargin }],
    ['ROI', { formula: 'B6/B4', result: result.financial.roi }]
  ]);
  cashFlow.addRow(['Month','Cost','Revenue','Net','Cumulative']);
  result.financial.monthlyCashFlow.forEach((row, index) => cashFlow.addRow([row.month, row.cost, row.revenue, { formula: `C${index + 2}-B${index + 2}`, result: row.net }, row.cumulative]));
  assumptions.addRows([
    ['Assumption','Value','Source','Status','User Override'],
    ['Sellable Efficiency', scenario.financial.sellableEfficiencyResidential, 'Suggested Benchmark', 'Suggested', 'Editable'],
    ['Active Regulation Pack', regulation.code, regulation.sourceReference, regulation.verificationStatus, 'No'],
    ['Parcel Applicability Confirmation', 'USER DOCUMENTED ONLY - NOT INDEPENDENTLY VERIFIED', scenario.regulationEvidence?.documentReference ?? 'NO EVIDENCE', scenario.regulationEvidence?.status ?? 'MISSING', 'No'],
    ['Applicability Justification', scenario.regulationEvidence?.applicabilityReason ?? 'NOT DOCUMENTED', 'User evidence', 'Not official verification', 'No'],
    ['Precedence / Conflict Resolution', scenario.regulationEvidence?.precedenceReason ?? 'NOT RESOLVED', 'User evidence', 'Not official verification', 'No'],
    ['Applicability Reviewed By', scenario.regulationEvidence?.reviewer ?? 'NOT RECORDED', 'User provided', 'Not official verification', 'No']
  ]);
  if (scenario.overrides.length) {
    assumptions.addRow([]);
    assumptions.addRow(['Rule','Regulatory Value','Used Value','Source','Reason']);
    scenario.overrides.forEach((override) => assumptions.addRow([override.field, override.originalValue === 'null' ? 'Not Defined' : override.originalValue, override.usedValue, 'USER_OVERRIDE', override.reason]));
  }
  sheets.forEach((sheet) => {
    sheet.columns.forEach((column) => { column.width = 24; });
    sheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' }, size: 16 };
    sheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1D6B5D' } };
    sheet.getRow(2).font = { color: { argb: 'FFD2A84F' }, bold: true };
    sheet.eachRow((row) => row.eachCell((cell) => {
      cell.border = { bottom: { style: 'thin', color: { argb: 'FFE8EBE6' } } };
      cell.alignment = { vertical: 'middle', horizontal: language === 'en' ? 'left' : 'right' };
    }));
  });
  const buffer = await wb.xlsx.writeBuffer();
  const exportResult = await desktopAPI().writeExport(`${project.info.name.replaceAll(' ', '_')}_SaudiDevelopIQ.xlsx`, bytes(buffer));
  if (!exportResult.success || !exportResult.filePath) throw new Error(exportResult.error || 'Excel export failed');
  return exportResult.filePath;
};

export const exportPdf = async (project: ProjectRecord, regulations: RegulationPack[], language: LanguageMode, company: CompanyProfile) => {
  const scenario = project.scenarios.find((s) => s.id === project.activeScenarioId) ?? project.scenarios[0];
  const regulation = project.regulationSnapshots.find((r) => r.id === scenario.regulationId) ?? regulations.find((r) => r.id === scenario.regulationId);
  if (!regulation) throw new Error('No active regulation snapshot selected for export.');
  const result = runScenario(scenario, regulation);
  const pdf = new jsPDF({ orientation: 'portrait', unit: 'pt', format: 'a4' });
  if (typeof document === 'undefined') throw new Error('PDF export requires renderer document context.');
  const pageW = 1240;
  const pageH = 1754;
  const margin = 74;
  const brand = '#155447';
  const gold = '#c9a24f';
  const ink = '#17211c';
  const muted = '#68736e';
  const line = '#dfe5df';
  const surface = '#fbfaf6';
  const fmt = (value: number) => Math.round(value).toLocaleString();
  const sar = (value: number) => `SAR ${(value / 1_000_000).toLocaleString(undefined, { maximumFractionDigits: 1 })} M`;
  const percent = (value: number) => `${Math.round(value * 100)}%`;
  const pages: string[] = [];
  const officialMark = await loadImage(officialAppIconUrl);
  const makePage = (title: string, draw: (ctx: CanvasRenderingContext2D) => void) => {
    const canvas = document.createElement('canvas');
    canvas.width = pageW;
    canvas.height = pageH;
    const ctx = canvas.getContext('2d');
    if (!ctx) throw new Error('Could not create PDF canvas.');
    ctx.fillStyle = surface;
    ctx.fillRect(0, 0, pageW, pageH);
    ctx.fillStyle = brand;
    ctx.fillRect(0, 0, 18, pageH);
    ctx.drawImage(officialMark, margin, 34, 120, 120);
    ctx.fillStyle = ink;
    ctx.font = '700 34px Segoe UI, Tahoma, Arial';
    ctx.textAlign = 'left';
    ctx.fillText(title, margin + 150, 84);
    ctx.fillStyle = muted;
    ctx.font = '500 18px Segoe UI, Tahoma, Arial';
    ctx.fillText('Saudi DevelopIQ - Riyadh Edition', margin + 150, 116);
    ctx.textAlign = 'right';
    ctx.fillText(company.companyNameEn || 'Saudi DevelopIQ', pageW - margin, 84);
    ctx.fillText(`Prepared by: ${company.preparedBy || 'Mahmoud Elgamsy'}`, pageW - margin, 116);
    ctx.textAlign = 'left';
    ctx.strokeStyle = line;
    ctx.lineWidth = 2;
    ctx.beginPath();
    ctx.moveTo(margin, 164);
    ctx.lineTo(pageW - margin, 164);
    ctx.stroke();
    draw(ctx);
    ctx.fillStyle = muted;
    ctx.font = '14px Segoe UI, Tahoma, Arial';
    ctx.fillText('Generated by Saudi DevelopIQ - Riyadh Edition', margin, pageH - 42);
    ctx.fillStyle = '#a14a29';
    ctx.font = '700 18px Segoe UI, Tahoma, Arial';
    ctx.fillText('PRELIMINARY - PARCEL REGULATION NOT INDEPENDENTLY VERIFIED', margin, pageH - 77);
    pages.push(canvas.toDataURL('image/png'));
  };
  const card = (ctx: CanvasRenderingContext2D, x: number, y: number, w: number, h: number, label: string, value: string, color = ink) => {
    ctx.fillStyle = '#ffffff';
    ctx.strokeStyle = line;
    ctx.lineWidth = 2;
    ctx.beginPath();
    ctx.roundRect(x, y, w, h, 18);
    ctx.fill();
    ctx.stroke();
    ctx.fillStyle = muted;
    ctx.font = '600 17px Segoe UI, Tahoma, Arial';
    ctx.fillText(label, x + 24, y + 42);
    ctx.fillStyle = color;
    let size = 34;
    do {
      ctx.font = `800 ${size}px Segoe UI, Tahoma, Arial`;
      size -= 2;
    } while (ctx.measureText(value).width > w - 48 && size >= 20);
    ctx.fillText(value, x + 24, y + 92);
  };
  const table = (ctx: CanvasRenderingContext2D, x: number, y: number, rows: string[][], widths: number[]) => {
    rows.forEach((row, r) => {
      const h = r === 0 ? 46 : 40;
      ctx.fillStyle = r === 0 ? brand : '#ffffff';
      ctx.fillRect(x, y, widths.reduce((a, b) => a + b, 0), h);
      let cx = x;
      row.forEach((cell, i) => {
        ctx.strokeStyle = line;
        ctx.strokeRect(cx, y, widths[i], h);
        ctx.fillStyle = r === 0 ? '#ffffff' : ink;
        ctx.font = `${r === 0 ? '700' : '500'} 17px Segoe UI, Tahoma, Arial`;
        ctx.fillText(String(cell), cx + 14, y + 29);
        cx += widths[i];
      });
      y += h;
    });
  };
  makePage('Executive Dashboard', (ctx) => {
    ctx.fillStyle = ink;
    ctx.font = '800 44px Segoe UI, Tahoma, Arial';
    ctx.fillText(project.info.name, margin, 245);
    ctx.fillStyle = muted;
    ctx.font = '500 22px Segoe UI, Tahoma, Arial';
    ctx.fillText(`${project.info.use} - Riyadh - ${project.info.district}`, margin, 282);
    card(ctx, margin, 350, 250, 130, 'Plot Area', `${fmt(result.envelope.plotArea)} m2`);
    card(ctx, margin + 280, 350, 250, 130, 'Final Footprint', `${fmt(result.envelope.finalFootprint)} m2`, brand);
    card(ctx, margin + 560, 350, 250, 130, 'Profit', sar(result.financial.profit), result.financial.profit >= 0 ? brand : '#a9482f');
    card(ctx, margin + 840, 350, 250, 130, 'ROI', percent(result.financial.roi), gold);
    card(ctx, margin, 540, 340, 140, 'Decision', L(result.decision.label, language), brand);
    card(ctx, margin + 380, 540, 340, 140, 'Parking', `${result.parking.providedSpaces}/${result.parking.requiredSpaces}`);
    card(ctx, margin + 760, 540, 330, 140, 'FAR Source', result.envelope.farSource);
    table(ctx, margin, 760, [
      ['Constraint', 'Area', 'How to read'],
      ['Setback / Geometry', `${fmt(result.envelope.geometricFootprint)} m2`, 'Net buildable area after setbacks/depth'],
      ['Coverage Limit', `${fmt(result.envelope.coverageLimit)} m2`, 'Plot area x regulation coverage'],
      ['Final Footprint', `${fmt(result.envelope.finalFootprint)} m2`, 'Minimum of geometry, coverage and FAR budget']
    ], [310, 220, 560]);
  });
  makePage('Plot, Envelope & Parking', (ctx) => {
    const x = margin;
    const y = 240;
    const w = 650;
    const h = 520;
    ctx.fillStyle = '#fffdf7';
    ctx.strokeStyle = brand;
    ctx.lineWidth = 4;
    ctx.strokeRect(x, y, w, h);
    ctx.fillStyle = '#d7b456';
    ctx.fillRect(x, y, w, 70);
    ctx.fillStyle = ink;
    ctx.font = '700 22px Segoe UI, Tahoma, Arial';
    ctx.textAlign = 'center';
    ctx.fillText('Front Street', x + w / 2, y + 45);
    ctx.strokeStyle = '#86a99a';
    ctx.setLineDash([12, 8]);
    ctx.strokeRect(x + 75, y + 115, w - 150, h - 190);
    ctx.setLineDash([]);
    ctx.fillStyle = 'rgba(21,84,71,.78)';
    const geoRatio = Math.min(1, result.envelope.finalFootprint / Math.max(1, result.envelope.geometricFootprint));
    ctx.fillRect(x + 135, y + 190, (w - 270) * Math.max(0.25, geoRatio), 150);
    ctx.fillStyle = '#ffffff';
    ctx.font = '800 34px Segoe UI, Tahoma, Arial';
    ctx.fillText(`${fmt(result.envelope.finalFootprint)} m2`, x + w / 2, y + 255);
    ctx.font = '500 20px Segoe UI, Tahoma, Arial';
    ctx.fillText('Final Allowed Footprint', x + w / 2, y + 292);
    ctx.textAlign = 'left';
    table(ctx, margin + 690, 240, [
      ['Metric', 'Value'],
      ['Geometry after setbacks', `${fmt(result.envelope.geometricFootprint)} m2`],
      ['Coverage limit', `${fmt(result.envelope.coverageLimit)} m2`],
      ['Final footprint', `${fmt(result.envelope.finalFootprint)} m2`],
      ['Front / Rear', `${result.envelope.setbacks.front}m / ${result.envelope.setbacks.rear}m`],
      ['Left / Right', `${result.envelope.setbacks.left}m / ${result.envelope.setbacks.right}m`]
    ], [205, 250]);
    table(ctx, margin, 850, [
      ['Parking item', 'Value'],
      ['Development use', scenario.developmentUse ?? 'Not defined'],
      ['Layout', result.parking.parkingLayout],
      ['Surface parking', `${result.parking.surfaceParking} (${result.parking.surfaceParkingMode})`],
      ['Spaces per basement', String(result.parking.spacesPerBasement)],
      ['Required basements after surface', String(result.parking.basementCountRequired)],
      ['Balance', String(result.parking.balance)]
    ], [360, 360]);
  });
  makePage('Development & Financial Detail', (ctx) => {
    table(ctx, margin, 230, [
      ['Floor', 'Coverage Limit', 'Geometry Limit', 'FAR Limit', 'Final Area'],
      ...result.envelope.floorAreas.map((row) => [row.floor, `${fmt(row.coverageLimit)} m2`, `${fmt(row.geometryLimit)} m2`, `${fmt(row.farLimit)} m2`, `${fmt(row.finalAllowedArea)} m2`])
    ], [230, 210, 210, 210, 230]);
    const startY = 620;
    table(ctx, margin, startY, [
      ['Financial Metric', 'Value'],
      ['Land Cost', sar(result.financial.landCost)],
      ['Construction Cost', sar(result.financial.constructionCost)],
      ['Soft Costs', sar(result.financial.softCosts)],
      ['Revenue', sar(result.financial.revenue)],
      ['Profit', sar(result.financial.profit)],
      ['ROI', percent(result.financial.roi)]
    ], [360, 280]);
    const chartX = margin + 700;
    const chartY = startY;
    const bars = [['Cost', result.financial.totalCost, '#766f63'], ['Revenue', result.financial.revenue, brand], ['Profit', Math.max(0, result.financial.profit), gold]] as const;
    const max = Math.max(...bars.map((bar) => bar[1]), 1);
    bars.forEach((bar, index) => {
      ctx.fillStyle = bar[2];
      ctx.fillRect(chartX + index * 120, chartY + 240 - (bar[1] / max) * 220, 70, (bar[1] / max) * 220);
      ctx.fillStyle = ink;
      ctx.font = '600 16px Segoe UI, Tahoma, Arial';
      ctx.fillText(bar[0], chartX + index * 120, chartY + 270);
    });
  });
  makePage('Sources, Overrides & Assumptions', (ctx) => {
    table(ctx, margin, 230, [
      ['Item', 'Value'],
      ['Regulation', L(regulation.name, language)],
      ['Status', regulation.verificationStatus],
      ['Parcel applicability', 'User documented only / Not officially verified'],
      ['Parcel evidence', scenario.regulationEvidence?.documentReference ?? 'Not recorded'],
      ['FAR source', result.envelope.farSource],
      ['How FAR calculated', result.envelope.farHowCalculated],
      ['Source reference', regulation.sourceReference]
    ], [310, 780]);
    const overrideRows = scenario.overrides.length
      ? scenario.overrides.map((override) => [override.field, override.originalValue === 'null' ? 'Not Defined' : override.originalValue, override.usedValue, override.source, override.reason])
      : [['None', '-', '-', '-', '-']];
    table(ctx, margin, 560, [['Rule', 'Regulatory', 'Used', 'Source', 'Reason'], ...overrideRows], [210, 210, 170, 210, 290]);
  });
  pages.forEach((page, index) => {
    if (index > 0) pdf.addPage();
    pdf.addImage(page, 'PNG', 0, 0, 595.28, 841.89);
  });
  const buffer = pdf.output('arraybuffer');
  const exportResult = await desktopAPI().writeExport(`${project.info.name.replaceAll(' ', '_')}_SaudiDevelopIQ.pdf`, bytes(buffer));
  if (!exportResult.success || !exportResult.filePath) throw new Error(exportResult.error || 'PDF export failed');
  return exportResult.filePath;
};
